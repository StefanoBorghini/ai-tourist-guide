// Dopo studio-territori-e2e.mjs (stesso stack): il territorio creato e pubblicato dallo Studio è usabile nella guida?
import { chromium } from "playwright";
import { readdirSync } from "node:fs";
const exe = readdirSync("/opt/pw-browsers").find((d) => d.startsWith("chromium-"));
const b = await chromium.launch({ executablePath: `/opt/pw-browsers/${exe}/chrome-linux/chrome`, args: ["--no-sandbox"] });
const BASE = "http://localhost:3100";
const NEW = "riviera-di-prova.borgo-dello-studio";
const results = [];
const check = (name, ok, extra = "") => { results.push(!!ok); console.log(`${ok ? "✓" : "✗"} ${name}${extra ? ` — ${extra}` : ""}`); };
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, locale: "it-IT", geolocation: { latitude: 44.1002, longitude: 9.9001, accuracy: 8 }, permissions: ["geolocation"] });
await ctx.addInitScript(() => {
  window.__spoken = [];
  window.SpeechSynthesisUtterance = class { constructor(t) { this.text = t; } };
  Object.defineProperty(window, "speechSynthesis", { configurable: true, value: { getVoices: () => [], pause() {}, resume() {}, cancel() {}, speak(u) { window.__spoken.push(u.text); setTimeout(() => u.onend && u.onend(), 200); } } });
});
const p = await ctx.newPage();
const errors = []; p.on("pageerror", (e) => errors.push(e.message));
await p.goto(BASE);
await p.evaluate(() => navigator.serviceWorker.ready);
await p.getByRole("button", { name: "Italiano", exact: true }).click();
await p.getByRole("button", { name: /Esplora Borgo dello Studio/ }).click();
await p.getByRole("heading", { name: /Percorsi guidati/ }).waitFor({ timeout: 15000 });
check("il territorio nuovo si apre (hub)", await p.getByRole("button", { name: "Inizia a esplorare" }).isVisible());
const hubButtons = (await p.locator("button").allTextContents()).map((t) => t.trim()).filter(Boolean);
check("hub: il percorso creato nello Studio è elencato", hubButtons.some((t) => /Giro della piazza/.test(t)), hubButtons.join(" | ").slice(0, 400));
await p.getByRole("button", { name: /Scarica per l'uso offline/ }).click();
await p.getByText(/Disponibile offline/).first().waitFor({ timeout: 20000 });
check("scaricato per l'uso offline", true);
await p.getByRole("button", { name: "Inizia a esplorare" }).click();
const gps = p.getByRole("button", { name: "Attiva il GPS" });
if (await gps.isVisible().catch(() => false)) await gps.click();
await p.waitForTimeout(2500);
check("mappa con il luogo del territorio", (await p.locator(".map-pin, .pin, [class*=pin]").count()) > 0);
await p.getByRole("button", { name: "Elenco" }).click();
check("elenco: il luogo creato nello Studio", await p.getByText("Piazza della Fontana").first().isVisible());
await p.getByText("Piazza della Fontana").first().click();
const listen = p.getByRole("button", { name: /Ascolta la storia|Riascolta/ }).first();
if (await listen.isVisible().catch(() => false)) await listen.click();
await p.waitForTimeout(2500);
const spoken = await p.evaluate(() => window.__spoken);
check("narrazione: la guida racconta il testo scritto nello Studio", spoken.some((s) => /1890/.test(s)), spoken.map((s) => s.slice(0, 60)).join(" | "));
const ask = await (await fetch(`${BASE}/api/guide/ask`)).json();
check("server delle domande: conosce il territorio nuovo (versione pubblicata)", (ask.bundles ?? []).some((x) => x.destination === NEW), `available=${ask.available}`);
const q = await fetch(`${BASE}/api/guide/ask`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ destination: NEW, locale: "it", question: "Di quando è la fontana?" }) });
check("domanda all'AI sul territorio nuovo (senza chiave API: risposta di riserva 503 attesa)", q.status === 503 || q.status === 200 || q.status === 400, `HTTP ${q.status}`);
await ctx.setOffline(true);
await p.reload();
await p.getByRole("button", { name: "Italiano", exact: true }).click();
await p.getByRole("button", { name: /Esplora Borgo dello Studio/ }).click();
await p.getByRole("button", { name: "Inizia a esplorare" }).click();
await p.getByRole("button", { name: "Elenco" }).click();
check("senza rete: il territorio nuovo si apre e mostra i luoghi", await p.getByText("Piazza della Fontana").first().isVisible().catch(() => false));
check("nessun errore JavaScript", errors.length === 0, errors.join(" | "));
await b.close();
console.log(`\n${results.filter(Boolean).length}/${results.length} controlli superati`);
